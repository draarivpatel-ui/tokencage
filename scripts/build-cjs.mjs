import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = await readFile(path.join(root, 'src', 'index.mjs'), 'utf8');
const checkMode = process.argv.includes('--check');

const EXPORT_NAMES = [
  'CODE',
  'RESULT_CODE',
  'TokenCageError',
  'validatePrefix',
  'validateKeyId',
  'validatePepper',
  'generateToken',
  'generateTokenDetails',
  'inspectToken',
  'isValidTokenFormat',
  'hashToken',
  'hashTokenAsync',
  'verifyTokenHash',
  'verifyTokenHashAsync',
  'createTokenVerifier',
  'verifyAndRotate',
  'createTokenRecord',
  'verifyTokenRecord',
  'hasScopes',
  'redactToken',
  'maskToken',
  'TokenValue',
  'createTokenValue',
  'extractBearerToken',
  'extractApiKeyHeader',
  'createTokenCage'
];

let body = source;
if (!body.startsWith("import crypto from 'node:crypto';")) {
  throw new Error('CJS transform could not find the node:crypto import');
}
body = body.replace("import crypto from 'node:crypto';", "const crypto = require('node:crypto');");
body = body.replace(/^export const /gm, 'const ');
body = body.replace(/^export class /gm, 'class ');
body = body.replace(/^export function /gm, 'function ');
body = body.replace(/^export async function /gm, 'async function ');
if (!body.includes('export default tokencage;')) {
  throw new Error('CJS transform could not find the default export');
}
body = body.replace('export default tokencage;', '');
if (/^export\s/m.test(body)) throw new Error('CJS transform left an export declaration behind');
if (/^import\s/m.test(body)) throw new Error('CJS transform left an import declaration behind');

const output = [
  "'use strict';",
  '',
  '/* Generated by scripts/build-cjs.mjs from src/index.mjs. Do not edit directly. */',
  '',
  body.trim(),
  '',
  'module.exports = {',
  ...EXPORT_NAMES.map((name) => '  ' + name + ','),
  '};',
  '',
  'module.exports.default = module.exports;',
  ''
].join('\n');

const target = path.join(root, 'dist', 'index.cjs');
if (checkMode) {
  let existing = '';
  try {
    existing = await readFile(target, 'utf8');
  } catch {
    existing = '';
  }
  if (existing !== output) {
    throw new Error('dist/index.cjs is not up to date; run node scripts/build-cjs.mjs');
  }
  process.stdout.write('dist/index.cjs is up to date\n');
} else {
  await mkdir(path.join(root, 'dist'), { recursive: true });
  await writeFile(target, output, 'utf8');
  process.stdout.write('dist/index.cjs generated from src/index.mjs\n');
}
