test('generated CJS uses require only for node:crypto', () => {
  const output = fs.readFileSync(path.join(root, 'dist', 'index.cjs'), 'utf8');
  const matches = output.match(/require\(/g) || [];
  assert.equal(matches.length, 1);
  assert.equal(output.includes("require('node:crypto')"), true);
});

test('source of truth has exactly one node built-in import', () => {
  const source = fs.readFileSync(path.join(root, 'src', 'index.mjs'), 'utf8');
  const matches = source.match(/^import\s/gm) || [];
  assert.equal(matches.length, 1);
  assert.equal(source.includes("import crypto from 'node:crypto';"), true);
});

