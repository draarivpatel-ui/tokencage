import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { MODULES, esm, cjs, root, strongPepper } from './helpers.mjs';

const exportNames = [
  'CODE',
  'RESULT_CODE',
  'TokenCageError',
  'validatePrefix',
  'validateKeyId',
  'validatePepper',
  'generateToken',
  'generateTokenDetails',
  'inspectToken',
  'isValidTokenFormat',
  'hashToken',
  'hashTokenAsync',
  'verifyTokenHash',
  'verifyTokenHashAsync',
  'createTokenVerifier',
  'verifyAndRotate',
  'createTokenRecord',
  'verifyTokenRecord',
  'hasScopes',
  'redactToken',
  'maskToken',
  'TokenValue',
  'createTokenValue',
  'extractBearerToken',
  'extractApiKeyHeader',
  'createTokenCage'
];

test('generated CommonJS build is up to date', () => {
  const output = execFileSync(process.execPath, [path.join(root, 'scripts', 'build-cjs.mjs'), '--check'], {
    cwd: root,
    encoding: 'utf8'
  });
  assert.match(output, /up to date/);
});

for (const [label, module] of MODULES) {
  test(label + ' exposes every public export', () => {
    for (const name of exportNames) {
      assert.notEqual(typeof module[name], 'undefined', name);
    }
  });

  test(label + ' generation and inspection parity smoke test', () => {
    const details = module.generateTokenDetails({ prefix: 'testapp', keyId: true });
    assert.equal(module.inspectToken(details.token).valid, true);
  });

  test(label + ' deterministic hmac parity smoke test', () => {
    const pepper = strongPepper();
    const token = module.generateToken({ prefix: 'testapp' });
    const encoded = module.hashToken(token, { pepper, version: 'v1' });
    assert.equal(module.verifyTokenHash(token, encoded, { pepper }), true);
  });

  test(label + ' redaction parity smoke test', () => {
    const details = module.generateTokenDetails({ prefix: 'testapp', keyId: true });
    assert.equal(module.redactToken(details.token), details.redacted);
  });

  test(label + ' header extraction parity smoke test', () => {
    const token = module.generateToken({ prefix: 'testapp' });
    assert.equal(module.extractBearerToken('Bearer ' + token), token);
    assert.equal(module.extractApiKeyHeader({ 'x-api-key': token }), token);
  });
}

test('ESM and CJS produce identical deterministic HMAC output', () => {
  const pepper = strongPepper();
  const token = 'deterministic-token';
  assert.equal(
    esm.hashToken(token, { pepper, version: 'v1' }),
    cjs.hashToken(token, { pepper, version: 'v1' })
  );
});

test('ESM and CJS produce identical inspection objects for the same token', () => {
  const token = esm.generateToken({ prefix: 'testapp', keyId: true });
  assert.deepEqual(cjs.inspectToken(token), esm.inspectToken(token));
});

test('ESM and CJS produce identical redaction output for the same token', () => {
  const token = esm.generateToken({ prefix: 'testapp', keyId: true });
  assert.equal(cjs.redactToken(token), esm.redactToken(token));
});

test('ESM and CJS error objects have the same code shape', () => {
  for (const module of [esm, cjs]) {
    let error;
    try { module.generateToken({ prefix: 'Bad' }); } catch (caught) { error = caught; }
    assert.equal(error.name, 'TokenCageError');
    assert.equal(error.code, 'ERR_TOKENCAGE_INVALID_PREFIX');
    assert.equal(typeof error.toJSON(), 'object');
  }
});

test('package self-reference resolves through ESM exports', async () => {
  const module = await import('tokencage');
  assert.equal(typeof module.generateToken, 'function');
  assert.equal(module.CODE.INVALID_INPUT, esm.CODE.INVALID_INPUT);
});

test('package self-reference resolves through CJS exports', () => {
  assert.equal(typeof cjs.generateToken, 'function');
  assert.equal(cjs.CODE.INVALID_INPUT, esm.CODE.INVALID_INPUT);
});

test('ESM default export contains the public API', async () => {
  const module = await import('../src/index.mjs');
  for (const name of exportNames) {
    assert.notEqual(typeof module.default[name], 'undefined', name);
  }
});

test('CJS default reference is the exported API object', () => {
  assert.equal(cjs.default, cjs);
});

